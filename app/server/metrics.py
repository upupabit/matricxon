"""Counters for `GET /metrics` (Prometheus text format), kept in memory since this process
started. Requests are counted by route template (`/api/chat`, never the full URL), so the list
stays short."""

import threading
from collections import defaultdict


class Metrics:
    _shared: "Metrics | None" = None

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._requests: dict[tuple[str, str, int], int] = defaultdict(int)
        self._seconds: dict[tuple[str, str], float] = defaultdict(float)
        self._calls: dict[tuple[str, str], int] = defaultdict(int)
        self._tokens = {"prompt": 0, "generated": 0}

    @classmethod
    def shared(cls) -> "Metrics":
        if cls._shared is None:
            cls._shared = cls()
        return cls._shared

    def request(self, method: str, route: str, status: int, seconds: float) -> None:
        with self._lock:
            self._requests[(method, route, status)] += 1
            self._seconds[(method, route)] += seconds
            self._calls[(method, route)] += 1

    def tokens(self, prompt: int, generated: int) -> None:
        """One finished reply's token counts (chat and generate)."""
        with self._lock:
            self._tokens["prompt"] += prompt
            self._tokens["generated"] += generated

    @staticmethod
    def _label(value: object) -> str:
        return str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")

    def text(self, gauges: dict[str, tuple[str, float]]) -> str:
        """The exposition text: these counters plus live `gauges` ({name: (help, value)})."""
        lines: list[str] = []

        def metric(name: str, kind: str, help_text: str) -> None:
            lines.extend([f"# HELP {name} {help_text}", f"# TYPE {name} {kind}"])

        with self._lock:
            metric("matricxon_requests_total", "counter", "HTTP requests by route and status.")
            for (method, route, status), count in sorted(self._requests.items()):
                labels = f'method="{method}",route="{self._label(route)}",status="{status}"'
                lines.append(f"matricxon_requests_total{{{labels}}} {count}")
            metric("matricxon_request_seconds", "summary", "Time to answer, to the last byte.")
            for (method, route), seconds in sorted(self._seconds.items()):
                labels = f'method="{method}",route="{self._label(route)}"'
                lines.append(f"matricxon_request_seconds_sum{{{labels}}} {seconds:.6f}")
                lines.append(
                    f"matricxon_request_seconds_count{{{labels}}} {self._calls[(method, route)]}"
                )
            metric("matricxon_prompt_tokens_total", "counter", "Prompt tokens read by replies.")
            lines.append(f"matricxon_prompt_tokens_total {self._tokens['prompt']}")
            metric("matricxon_generated_tokens_total", "counter", "Tokens generated by replies.")
            lines.append(f"matricxon_generated_tokens_total {self._tokens['generated']}")
        for name, (help_text, value) in sorted(gauges.items()):
            metric(name, "gauge", help_text)
            lines.append(f"{name} {value}")
        return "\n".join(lines) + "\n"
